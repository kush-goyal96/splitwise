"""HTTP side of Idempotency-Key support for POSTs that record money (decision 10 in DESIGN.md).

The client generates a random UUID once per user action and sends it on every retry of
that action. The server stores it on the row it creates, with a fingerprint of the
request, so a retry returns the original row instead of recording the money twice.
"""

import hashlib
import json
import uuid
from typing import Annotated, Any

from fastapi import Header

IdempotencyKey = Annotated[
    uuid.UUID | None,
    Header(
        alias="Idempotency-Key",
        description=(
            "Optional. A random UUID generated by the client once per action and reused on "
            "every retry of it. A retry returns the original result instead of creating a duplicate."
        ),
    ),
]

# Set to "true" on a response that returns the result of an earlier request with the same key.
REPLAYED_HEADER = "Idempotent-Replayed"


def fingerprint(canonical_data: dict[str, Any]) -> str:
    """SHA-256 of the request's canonical form (see fingerprint_data() on the schemas).

    It is a check, not the key: it only detects a key reused for a *different* request.
    """
    encoded = json.dumps(canonical_data, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(encoded).hexdigest()
